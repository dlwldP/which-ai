// 에이전트 지침이 낡지 않게: AGENTS.md에 적은 경로가 실제로 있는지, CLAUDE.md가 원본을 불러오기만 하는지.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { findAttribution } from '../scripts/check-attribution.js';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');

/** `js/app.js`처럼 백틱 안에 적은 저장소 경로 (폴더는 끝이 /) */
export function repoPaths(text) {
  const out = new Set();
  for (const [, p] of text.matchAll(/`([^`\s]+)`/g)) {
    if (/^(\.github|\.claude|js|css|data|docs|drafts|scripts|tests|dev)\/[^*?]*$/.test(p) || /^[\w.-]+\.(md|html|json|xml)$/.test(p)) out.add(p);
  }
  return [...out];
}

test('CLAUDE.md는 AGENTS.md를 불러오기만 함 (규칙을 두 곳에 쓰지 않음)', () => {
  assert.equal(read('CLAUDE.md').trim(), '@AGENTS.md');
});

test('AGENTS.md에 적은 파일·폴더가 모두 실제로 있음', () => {
  const paths = repoPaths(read('AGENTS.md'));
  assert.ok(paths.length > 20, `경로를 거의 못 찾음: ${paths.length}개`);
  const missing = paths.filter((p) => !existsSync(new URL(p, root)));
  assert.deepEqual(missing, []);
});

test('AGENTS.md의 "수정하지 않는 파일"은 .claude/settings.json에서도 묻도록 설정됨', () => {
  const ask = JSON.parse(read('.claude/settings.json')).permissions.ask.join('\n');
  for (const p of ['.github', 'js/analytics.js', 'js/pages.js', 'js/feedback.js', 'git push origin main']) assert.ok(ask.includes(p), p);
});

test('작성 도구 표시 찾기', () => {
  assert.equal(findAttribution('## 바뀐 것\n- 통계 고침').length, 0);
  assert.deepEqual(findAttribution('본문\n\n_Generated by [Claude Code](https://claude.ai/code/session_x)_').map((f) => f.line), [3]);
  assert.equal(findAttribution('Co-Authored-By: someone <a@b.c>').length, 1);
  assert.equal(findAttribution('🤖 Generated with Claude Code').length, 1);
});
